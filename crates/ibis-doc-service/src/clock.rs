//! The time for the tools that stamp what they write (a comment's date, a date picker): the only place of this crate that reads the clock. The crate is not built for
//! the browser (the MCP server and the assistant over standard input and output), so the std clock is read here.
#![allow(clippy::disallowed_methods)]

/// Seconds since 1970-01-01 UTC.
pub(crate) fn unix_seconds() -> i64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_secs() as i64)
}

/// The time now as `w:date` writes it (`2026-10-01T09:00:00Z`), to the minute as Word does.
pub(crate) fn now_utc() -> String {
    let secs = unix_seconds() / 60 * 60;
    let (days, rest) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // Days since 1970-01-01 to a civil date (Howard Hinnant's algorithm).
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!("{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}Z", rest / 3600, rest % 3600 / 60, rest % 60)
}
