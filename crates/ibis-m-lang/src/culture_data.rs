//! The data of each culture: what Windows (NLS, the data .NET's `CultureInfo` gives) holds for it, as Microsoft 365 Excel's Power Query on
//! Windows 11 gave it (`tests/data/k0039-locales-result.tsv`: patterns of the standard formats, names, designators, separators and the
//! currency and percent patterns). Nothing here is derived from the measured table by a factor: every entry is a value of the culture's
//! own data. The invariant culture (the empty name) is .NET's `InvariantCulture`; of it only the short date was measured.

/// The order a date written in numbers is read in (what the culture's patterns try).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum DateOrder {
    /// `yyyy/M/d`, with a two-digit year first too; `M/d/yyyy` when the year has four digits (ja-JP, zh-CN).
    YearFirst,
    /// `M/d/yyyy` and `M/d/yy` (en-US, the invariant culture).
    MonthFirst,
    /// `d/M/yyyy` and `d/M/yy` (de-DE, fr-FR, en-GB, th-TH).
    DayFirst,
}

pub struct Data {
    pub name: &'static str,
    pub months: [&'static str; 12],
    pub months_abbr: [&'static str; 12],
    /// Sunday first.
    pub days: [&'static str; 7],
    pub days_abbr: [&'static str; 7],
    pub am: &'static str,
    pub pm: &'static str,
    /// The era's name (`gg`).
    pub era: &'static str,
    /// The calendar is the Thai Buddhist one: the year is the Gregorian year + 543.
    pub buddhist: bool,
    /// The date separator (`/` in a custom format).
    pub date_sep: &'static str,
    pub short_date: &'static str,
    pub long_date: &'static str,
    /// The long date of the Gregorian calendar (the `U` format is always Gregorian); th-TH's own long date has no weekday.
    pub universal_date: &'static str,
    pub month_day: &'static str,
    pub year_month: &'static str,
    pub short_time: &'static str,
    pub long_time: &'static str,
    pub date_order: DateOrder,
    /// The last year a two-digit year can mean, in the culture's calendar (`TwoDigitYearMax`).
    pub two_digit_year_max: i64,
    pub decimal: &'static str,
    pub group: &'static str,
    /// `¤` is the symbol, `n` the number.
    pub currency: &'static str,
    pub currency_decimals: usize,
    pub currency_pos: &'static str,
    pub currency_neg: &'static str,
    pub percent_pos: &'static str,
    pub percent_neg: &'static str,
}

